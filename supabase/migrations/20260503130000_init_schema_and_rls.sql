  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint team_events_title_length_check check (char_length(title) between 1 and 120),
  constraint team_events_summary_length_check check (char_length(summary) <= 280)
