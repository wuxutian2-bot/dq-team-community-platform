-- DQ战队成长记录与成员社区平台
-- Step 03: Database schema + RLS
--
-- Important operational notes:
-- 1. Disable public signup in Supabase Auth settings. Member accounts should be created by admins only.
-- 2. New auth users are bootstrapped into public.profiles as role_level = 4 and status = 'pending'.
-- 3. Promote the first captain manually after creating the first auth account, for example:
--    update public.profiles
--    set role_level = 1, status = 'active'
--    where email = 'captain@example.com';

create schema if not exists private;

revoke all on schema private from public;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text unique,
  username text,
  display_name text not null,
  bio text not null default '',
  avatar_path text,
  banner_path text,
  favorite_game text,
  position_title text,
  joined_at date not null default current_date,
  role_level smallint not null default 4,
  status text not null default 'pending',
  is_profile_public boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint profiles_role_level_check check (role_level between 1 and 4),
  constraint profiles_status_check check (status in ('pending', 'active', 'disabled')),
  constraint profiles_username_length_check check (
    username is null or char_length(username) between 3 and 24
  ),
  constraint profiles_display_name_length_check check (
    char_length(display_name) between 1 and 40
  ),
  constraint profiles_bio_length_check check (char_length(bio) <= 500)
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles (id) on delete cascade,
  title text not null,
  excerpt text not null default '',
  content text not null default '',
  cover_image_path text,
  visibility text not null default 'public',
  status text not null default 'published',
  comments_enabled boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint posts_title_length_check check (char_length(title) between 1 and 120),
  constraint posts_excerpt_length_check check (char_length(excerpt) <= 280),
  constraint posts_visibility_check check (visibility in ('public', 'members')),
  constraint posts_status_check check (status in ('draft', 'published', 'hidden', 'archived'))
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  author_id uuid not null references public.profiles (id) on delete cascade,
  parent_id bigint references public.comments (id) on delete cascade,
  content text not null,
  status text not null default 'visible',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint comments_content_length_check check (char_length(content) between 1 and 2000),
  constraint comments_status_check check (status in ('visible', 'hidden', 'deleted'))
);

create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default timezone('utc', now()),
  constraint likes_post_user_unique unique (post_id, user_id)
);

create table if not exists public.team_events (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null default '',
  content text not null default '',
  event_date date not null,
  cover_image_path text,
