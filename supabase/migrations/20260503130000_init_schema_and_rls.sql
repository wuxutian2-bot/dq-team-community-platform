create or replace function private.is_captain()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select private.is_authenticated() and private.current_role_level() = 1;
$$;

create or replace function private.is_live_window(target_starts_at timestamptz, target_ends_at timestamptz)
returns boolean
language sql
stable
as $$
  select
    coalesce(target_starts_at, '-infinity'::timestamptz) <= now()
    and coalesce(target_ends_at, 'infinity'::timestamptz) >= now();
$$;

create or replace function private.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.profiles (
    id,
    email,
    display_name,
    status,
    role_level,
    is_profile_public
  )
  values (
    new.id,
    new.email,
    coalesce(
      new.raw_user_meta_data ->> 'display_name',
      split_part(coalesce(new.email, 'dq-member'), '@', 1),
      'DQ Member'
    ),
    'pending',
    4,
    true
  )
  on conflict (id) do update
  set
    email = excluded.email,
    updated_at = timezone('utc', now());

  return new;
end;
$$;

create or replace function private.sync_profile_email_from_auth()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles
    set
      email = new.email,
      updated_at = timezone('utc', now())
    where id = new.id;
  end if;

  return new;
end;
$$;

create or replace function private.protect_profile_admin_fields()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if (select auth.uid()) is null then
    return new;
  end if;

  if private.is_captain() then
    return new;
  end if;

  if new.role_level is distinct from old.role_level then
    raise exception 'Only the captain can change role_level.';
  end if;

  if not private.can_manage_members() then
    if new.status is distinct from old.status then
      raise exception 'Only vice-captain or captain can change member status.';
    end if;

    if new.email is distinct from old.email then
      raise exception 'Members cannot change synced email from profiles.';
    end if;

    if new.joined_at is distinct from old.joined_at then
      raise exception 'Members cannot change joined_at.';
    end if;
  end if;

  return new;
end;
$$;

create or replace function private.stamp_managed_content_actor()
returns trigger
language plpgsql
as $$
begin
  if (select auth.uid()) is not null then
    if tg_op = 'INSERT' then
      new.created_by := coalesce(new.created_by, (select auth.uid()));
    end if;

    new.updated_by := (select auth.uid());
  end if;

  return new;
end;
$$;

