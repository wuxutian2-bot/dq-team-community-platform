create or replace function private.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

create or replace function private.current_role_level()
returns smallint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(
    (
      select p.role_level
      from public.profiles as p
      where p.id = (select auth.uid())
    ),
    4::smallint
  );
$$;

create or replace function private.is_authenticated()
returns boolean
language sql
stable
as $$
  select (select auth.uid()) is not null;
$$;

create or replace function private.is_member()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select private.is_authenticated() and private.current_role_level() between 1 and 3;
$$;

create or replace function private.can_manage_content()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
